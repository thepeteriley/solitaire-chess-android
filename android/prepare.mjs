import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const android=path.dirname(fileURLToPath(import.meta.url)),root=path.dirname(android);
execFileSync('npm',['run','build'],{cwd:root,stdio:'inherit'});
const assets=path.join(android,'app/src/main/assets'),web=path.join(assets,'web');
await fs.mkdir(assets,{recursive:true});await fs.rm(web,{recursive:true,force:true});await fs.cp(path.join(root,'dist'),web,{recursive:true});
await fs.copyFile(path.join(android,'mobile.css'),path.join(web,'mobile.css'));
await fs.copyFile(path.join(android,'native-bridge.js'),path.join(web,'native-bridge.js'));
let html=await fs.readFile(path.join(web,'index.html'),'utf8');
html=html.replace('type="module" crossorigin','defer').replaceAll(' crossorigin','').replace('</head>','<script src="./native-bridge.js"></script><link rel="stylesheet" href="./mobile.css"></head>');
html=html.replace("connect-src 'self' ws://127.0.0.1:* http://127.0.0.1:*", "connect-src 'none'; frame-src 'none'; object-src 'none'");
await fs.writeFile(path.join(web,'index.html'),html);
const model=path.join(android,'engine-resources/nn-1a298aa575a0.nnue');
const checksum=createHash('sha256').update(await fs.readFile(model)).digest('hex');
if(checksum!=='1a298aa575a085434d29027978dc36867fe9c5bcea9376654b7a8eba1e52dfc2')throw Error('Engine model checksum mismatch.');
await fs.copyFile(model,path.join(assets,path.basename(model)));
await fs.copyFile(path.join(android,'Vendor/Stockfish/Copying.txt'),path.join(assets,'COPYING'));
const notices=await Promise.all(['react','react-dom','scheduler','chess.js'].map(async name=>name+'\n'+await fs.readFile(path.join(root,'node_modules',name,'LICENSE'),'utf8')));
for(const name of ['Shared-interface-MIT-LICENSE.txt','Android-NDK-NOTICE.txt'])notices.push(name+'\n'+await fs.readFile(path.join(android,'third-party',name),'utf8'));
await fs.writeFile(path.join(assets,'ThirdPartyNotices.txt'),notices.join('\n\n'));
